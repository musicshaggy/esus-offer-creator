const { app, BrowserWindow, dialog, session } = require('electron');
const path = require('path');
const fs = require('fs');
const assert = require('assert/strict');
const root = path.join(__dirname, '..');
require(path.join(root, 'main.js'));
const data = path.join(__dirname, 'desktop-data', 'close-test');
fs.mkdirSync(data, { recursive: true });
app.setPath('userData', data);
fs.writeFileSync(path.join(data, 'user-settings.json'), JSON.stringify({ initials: 'QA', profile: { fullName: 'Close Test', email: 'test@example.org', phone: '030123456', initials: 'QA' } }));
let choice = 0;
let prompts = 0;
dialog.showMessageBoxSync = () => { prompts++; return choice; };
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const keepAlive = new BrowserWindow({ show: false });
  try {
    session.defaultSession.webRequest.onBeforeRequest({ urls: ['https://api.nbp.pl/*'] }, (_details, callback) => callback({ cancel: true }));
    await wait(1400);
    const clean = BrowserWindow.getAllWindows().find(window => window.webContents.getURL().endsWith('/renderer/index.html'));
    assert.ok(clean);
    await clean.webContents.executeJavaScript(`document.querySelector('#btnWinClose').click()`);
    await wait(250);
    assert.ok(clean.isDestroyed(), 'X closes an unchanged window');
    assert.equal(prompts, 0);
    const dirty = new BrowserWindow({ show: false, webPreferences: { preload: path.join(root, 'preload.js'), contextIsolation: true, nodeIntegration: false } });
    await dirty.loadFile(path.join(root, 'renderer/index.html'));
    await wait(1000);
    await dirty.webContents.executeJavaScript(`document.querySelector('#btnOffersInvoices').click()`);
    await wait(1000);
    await dirty.webContents.executeJavaScript(`const input=document.querySelector('[data-field="number"]');input.value='UNSAVED';input.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('#btnWinClose').click()`);
    await wait(250);
    assert.equal(prompts, 1);
    assert.equal(dirty.isDestroyed(), false, 'Continue editing keeps the app open');
    choice = 1;
    await dirty.webContents.executeJavaScript(`document.querySelector('#btnWinClose').click()`);
    await wait(250);
    assert.equal(prompts, 2);
    assert.ok(dirty.isDestroyed(), 'Discard closes the app');
    console.log('PASS: X closes unchanged; dirty cancel preserves window; dirty discard closes');
    keepAlive.destroy();
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
